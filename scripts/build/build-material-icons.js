'use strict';
// Bundle the upstream VS Code associations and SVG assets, without a runtime dependency.
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..', '..');
const source = path.join(root, 'node_modules', 'material-icon-theme');
const target = path.join(root, 'src', 'assets', 'material-icons');
const manifest = JSON.parse(fs.readFileSync(path.join(source, 'dist', 'material-icons.json'), 'utf8'));
const version = JSON.parse(fs.readFileSync(path.join(source, 'package.json'), 'utf8')).version;
fs.mkdirSync(path.join(target, 'icons'), { recursive: true });
let bytes = 0;
for (const definition of Object.values(manifest.iconDefinitions)) {
    const name = path.basename(definition.iconPath);
    const svg = fs.readFileSync(path.join(source, 'icons', name));
    fs.writeFileSync(path.join(target, 'icons', name), svg);
    definition.iconPath = 'assets/material-icons/icons/' + name;
    bytes += svg.length;
}
fs.writeFileSync(path.join(target, 'manifest.js'), '// Material Icon Theme ' + version + ' (MIT); generated by scripts/build/build-material-icons.js\nwindow.MaterialIconManifest = ' + JSON.stringify(manifest) + ';\n');
const license = path.join(root, 'src', 'assets', 'licenses', 'material-icon-theme');
fs.mkdirSync(license, { recursive: true });
fs.copyFileSync(path.join(source, 'LICENSE'), path.join(license, 'LICENSE'));
fs.writeFileSync(path.join(license, 'NOTICE.md'), `Material Icon Theme ${version}\n\nSource: https://github.com/material-extensions/vscode-material-icon-theme\nMarketplace: https://marketplace.visualstudio.com/items?itemName=PKief.material-icon-theme\n\nSVGs and filename/folder associations are bundled from the official npm package, under the accompanying MIT license.\n`);
console.log(`Material Icon Theme ${version}: ${Object.keys(manifest.iconDefinitions).length} icons, ${(bytes / 1024 / 1024).toFixed(2)} MiB SVGs`);
